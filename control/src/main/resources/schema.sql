-- Portable between H2 (PostgreSQL mode, dev/test) and PostgreSQL. All timestamps are epoch millis.
CREATE TABLE IF NOT EXISTS clients (
  id            VARCHAR(36) PRIMARY KEY,
  name          VARCHAR(100) NOT NULL UNIQUE,
  description   VARCHAR(500),
  environment   VARCHAR(30) NOT NULL,
  credential_ref VARCHAR(200) NOT NULL,
  enabled       BOOLEAN NOT NULL,
  created_by    VARCHAR(100) NOT NULL,
  created_at    BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS api_defs (
  id            VARCHAR(36) PRIMARY KEY,
  service       VARCHAR(100) NOT NULL,
  operation     VARCHAR(100) NOT NULL,
  method        VARCHAR(10) NOT NULL,
  path_template VARCHAR(500) NOT NULL,
  access        VARCHAR(10) NOT NULL,
  updated_by    VARCHAR(100) NOT NULL,
  updated_at    BIGINT NOT NULL,
  UNIQUE (service, operation)
);

CREATE TABLE IF NOT EXISTS tasks (
  id             VARCHAR(36) PRIMARY KEY,
  name           VARCHAR(200) UNIQUE,
  created_by     VARCHAR(100) NOT NULL,
  created_at     BIGINT NOT NULL,
  latest_version INT NOT NULL
);

CREATE TABLE IF NOT EXISTS task_versions (
  id          VARCHAR(36) PRIMARY KEY,
  task_id     VARCHAR(36) NOT NULL REFERENCES tasks(id),
  ver         INT NOT NULL,
  client_id   VARCHAR(36) NOT NULL REFERENCES clients(id),
  script      TEXT NOT NULL,
  script_hash VARCHAR(64) NOT NULL,
  meta_json   TEXT NOT NULL,
  params_json TEXT NOT NULL,
  ops_json    TEXT NOT NULL,
  created_by  VARCHAR(100) NOT NULL,
  created_at  BIGINT NOT NULL,
  UNIQUE (task_id, ver)
);

CREATE TABLE IF NOT EXISTS runs (
  id               VARCHAR(36) PRIMARY KEY,
  task_id          VARCHAR(36) NOT NULL REFERENCES tasks(id),
  ver              INT NOT NULL,
  client_id        VARCHAR(36) NOT NULL REFERENCES clients(id),
  params_json      TEXT NOT NULL,
  submitted_by     VARCHAR(100) NOT NULL,
  status           VARCHAR(20) NOT NULL,
  approval_hash    VARCHAR(64) NOT NULL,
  requires_approval BOOLEAN NOT NULL,
  approved_by      VARCHAR(100),
  created_at       BIGINT NOT NULL,
  started_at       BIGINT,
  finished_at      BIGINT,
  heartbeat_at     BIGINT,
  node             VARCHAR(100),
  cancel_requested BOOLEAN NOT NULL,
  result_json      TEXT,
  error            TEXT
);
CREATE INDEX IF NOT EXISTS runs_status ON runs (status, created_at);

CREATE TABLE IF NOT EXISTS run_events (
  id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id  VARCHAR(36) NOT NULL,
  ts      BIGINT NOT NULL,
  kind    VARCHAR(10) NOT NULL,
  lvl     VARCHAR(10),
  message TEXT
);
CREATE INDEX IF NOT EXISTS run_events_run ON run_events (run_id, id);

CREATE TABLE IF NOT EXISTS api_call_audit (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id      VARCHAR(36) NOT NULL,
  ts          BIGINT NOT NULL,
  service     VARCHAR(100) NOT NULL,
  operation   VARCHAR(100) NOT NULL,
  method      VARCHAR(10) NOT NULL,
  path        VARCHAR(500) NOT NULL,
  status      INT,
  duration_ms BIGINT,
  error       VARCHAR(500)
);
CREATE INDEX IF NOT EXISTS api_call_audit_run ON api_call_audit (run_id, id);

CREATE TABLE IF NOT EXISTS audit_log (
  id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ts     BIGINT NOT NULL,
  actor  VARCHAR(100) NOT NULL,
  action VARCHAR(50) NOT NULL,
  target VARCHAR(200),
  detail TEXT
);

CREATE TABLE IF NOT EXISTS settings (
  k VARCHAR(50) PRIMARY KEY,
  v VARCHAR(500) NOT NULL
);
